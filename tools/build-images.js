/* Pre-compute illustration image URLs for every built-in deck word.
   Sources (free, no key): Wikipedia page thumbnail → Wikimedia Commons file search (title match, then full text) → Openverse.
   Output: data/images.js  →  VL.IMAGES = { "<lowercased word>": "<thumbnail url>", ... }
   Run: node tools/build-images.js [--force]   (resumable: keeps results in tools/.images-cache.json) */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const CACHE = path.join(__dirname, '.images-cache.json');
const OUT = path.join(ROOT, 'data', 'images.js');
const UA = 'VocaLab-image-builder/1.0 (static vocabulary learning app)';
const CONCURRENCY = 10;

const rows = [];
const ctx = { VL: { registerDeck: (id, r) => r.forEach((x) => rows.push({ w: x[0], pos: x[1], ex: x[4] || '' })) } };
vm.createContext(ctx);
fs.readdirSync(path.join(ROOT, 'data', 'decks')).filter((f) => f.endsWith('.js')).forEach((f) => vm.runInContext(fs.readFileSync(path.join(ROOT, 'data', 'decks', f), 'utf8'), ctx));
const seen = new Set();
const words = rows.filter((r) => { const k = r.w.trim().toLowerCase(); if (seen.has(k)) return false; seen.add(k); return true; });

const cache = fs.existsSync(CACHE) && !process.argv.includes('--force') ? JSON.parse(fs.readFileSync(CACHE, 'utf8')) : {};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJSON(url, tries) {
  tries = tries || 3;
  for (let i = 0; i < tries; i++) {
    try {
      const r = await fetch(url, { headers: { 'User-Agent': UA, Accept: 'application/json' }, signal: AbortSignal.timeout(8000) });
      if (r.status === 429 || r.status >= 500) { await sleep(1500 * (i + 1)); continue; }
      if (!r.ok) return null;
      return await r.json();
    } catch (e) { await sleep(800 * (i + 1)); }
  }
  return null;
}
const BAD = /(logo|icon|flag|map|coat[_ ]of[_ ]arms|signature|diagram|chart|svg|seal|pdf|djvu)/i;

async function wiki(term) {
  const j = await getJSON('https://en.wikipedia.org/api/rest_v1/page/summary/' + encodeURIComponent(term.replace(/\s+/g, '_')));
  if (!j || j.type === 'disambiguation' || !j.thumbnail) return null;
  return BAD.test(j.thumbnail.source) ? null : j.thumbnail.source;
}
async function commons(q) {
  const url = 'https://commons.wikimedia.org/w/api.php?action=query&format=json&generator=search&gsrnamespace=6&gsrlimit=8&prop=imageinfo&iiprop=url|mime&iiurlwidth=360&gsrsearch=' + encodeURIComponent(q);
  const j = await getJSON(url);
  const pages = j && j.query && j.query.pages ? Object.values(j.query.pages).sort((a, b) => a.index - b.index) : [];
  const hit = pages.find((p) => p.imageinfo && p.imageinfo[0] && /jpeg|png|webp/.test(p.imageinfo[0].mime) && !BAD.test(p.title));
  return hit ? hit.imageinfo[0].thumburl : null;
}
async function openverse(q) {
  const j = await getJSON('https://api.openverse.org/v1/images/?page_size=3&mature=false&q=' + encodeURIComponent(q));
  const hit = j && (j.results || []).find((x) => x.thumbnail || x.url);
  return hit ? hit.thumbnail || hit.url : null;
}

async function find(r) {
  const term = r.w.trim();
  const concrete = r.pos === 'n' || r.pos === 'exp';
  let url = null;
  if (concrete) url = await wiki(term);
  if (!url) url = await commons('intitle:"' + term + '" filetype:bitmap');
  if (!url) url = await commons(term + ' filetype:bitmap');
  if (!url && !concrete) url = await wiki(term);
  if (!url) url = await openverse(term);
  return url;
}

(async () => {
  let done = 0, found = 0;
  const todo = words.filter((r) => !(r.w.toLowerCase() in cache));
  console.log('words:', words.length, 'to look up:', todo.length);
  let i = 0;
  const save = () => fs.writeFileSync(CACHE, JSON.stringify(cache));
  await Promise.all(Array.from({ length: CONCURRENCY }, async () => {
    while (i < todo.length) {
      const r = todo[i++];
      cache[r.w.toLowerCase()] = await find(r);
      done++;
      if (done % 50 === 0) { save(); console.log(done + '/' + todo.length); }
      await sleep(50);
    }
  }));
  save();
  const out = {};
  words.forEach((r) => { const u = cache[r.w.toLowerCase()]; if (u) { out[r.w.toLowerCase()] = u; found++; } });
  fs.writeFileSync(OUT, '/* Illustration image URLs for built-in deck words (Wikipedia / Wikimedia Commons / Openverse thumbnails).\n   Generated by tools/build-images.js — ' + found + ' of ' + words.length + ' words. */\nVL.IMAGES = ' + JSON.stringify(out) + ';\n');
  console.log('found', found, 'of', words.length, '→', OUT);
})();
